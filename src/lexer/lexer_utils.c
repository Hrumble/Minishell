#include "libft.h"

int	ft_iswrd(int c)
{
	return (ft_isalnum(c) || c == '.' || c == '-' || c == '$');
}

int	ft_isspace(int c)
{
	return (c == ' ' || (c == '\t' && c == '\r'));
}
